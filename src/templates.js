import { sequenceSkeleton } from './skeleton.js';
import { GREETING, WORD_CAP } from './render.js';

// Outputs: templates.md, the brief's "templates with variables", from the snippet library and the skeleton module alone.
// No contacts: each skeleton comes from one representative routing result, and each place is shown as its snippet type.

// One representative routing result per step 1 shape. Steps 2 and 3 come from the trigger lead call.
const TRIGGER_LEAD = {
  lead_signal: 'Trigger',
  campaign: 'Scaling Fast',
  trigger_subtype: 'funding',
  angle: 'Employee Requests',
  band: 'Practitioner',
  cta_type: 'Practitioner',
  supporting_signal: 'System of record',
  system_of_record: 'BambooHR',
  workday: false,
};
const LEAD_LINE = {
  ...TRIGGER_LEAD,
  lead_signal: 'System of record',
  campaign: 'Evergreen',
  trigger_subtype: null,
  supporting_signal: 'Headcount trajectory',
};
const FLOOR = { ...TRIGGER_LEAD, lead_signal: 'Floor', campaign: 'Evergreen', trigger_subtype: null, cta_type: 'Floor', supporting_signal: null };

// A Snippet ID's type is its first segment: trigger.funding → {trigger}.
const typeOf = id => id.split('.')[0];
const place = id => `{${typeOf(id)}}`;

const STEP = { 1: 'Step 1: first touch', 2: 'Step 2: follow-up', 3: 'Step 3: closing note' };

// What each snippet type is called in the glossary.
const TYPE_NAME = {
  subject: 'Subject, by angle',
  trigger: 'Trigger snippet, by trigger sub-type',
  bridge: 'Bridge, by campaign × angle',
  lead: 'Lead line',
  support: 'Supporting line',
  mechanism: 'Mechanism line, by angle × band',
  proof: 'Proof line, by band',
  floor: 'Floor snippet, by angle',
  cta: 'CTA, by band',
  example: 'Example line, by angle',
  followup_cta: 'Follow-up CTA, by band',
  closing: 'Closing note, by angle',
};

// One email's skeleton: subject, greeting, its paragraphs of snippet places, then the signature.
function skeletonText(subject, paragraphs, library) {
  const body = paragraphs.map(ids => ids.map(place).join(' ')).join('\n\n');
  return [`Subject: ${subject}`, '', GREETING, '', body, '', library.signature].join('\n');
}

const skeletonBlock = (subject, paragraphs, library) => ['```text', skeletonText(subject, paragraphs, library), '```'].join('\n');

// The trigger-lead first touch as plain text, for the deck.
export function triggerSkeleton(library) {
  const { subject, emails } = sequenceSkeleton(TRIGGER_LEAD);
  return skeletonText(place(subject), emails[0], library);
}

// Each skeleton's body on one line, paragraphs joined by →, for the deck: the three first touches, then steps 2 and 3.
export function skeletonBodies() {
  const line = paragraphs => paragraphs.map(ids => ids.map(place).join(' ')).join(' → ');
  const trigger = sequenceSkeleton(TRIGGER_LEAD);
  return {
    trigger: line(trigger.emails[0]),
    lead: line(sequenceSkeleton(LEAD_LINE).emails[0]),
    floor: line(sequenceSkeleton(FLOOR).emails[0]),
    followUp: line(trigger.emails[1]),
    closing: line(trigger.emails[2]),
  };
}

// Every snippet with its first variant, grouped by type in library order.
function snippetSections(library) {
  const byType = Map.groupBy(Object.entries(library.snippets), ([id]) => typeOf(id));
  return [...byType].flatMap(([type, snippets]) => [
    `### \`{${type}}\`${TYPE_NAME[type] ? ` ${TYPE_NAME[type]}` : ''}`,
    ['| Snippet ID | Variant 1 |', '| --- | --- |', ...snippets.map(([id, [v1]]) => `| \`${id}\` | ${v1.replaceAll('|', '\\|')} |`)].join('\n'),
  ]);
}

// Every {slot} the library fills from the contact or its rep, in the order it first appears.
const slotsIn = library => {
  const texts = [GREETING, ...Object.values(library.snippets).flat(), library.follow_up_subject, library.signature];
  return [...new Set(texts.flatMap(text => [...text.matchAll(/\{(\w+)\}/g)].map(m => `\`{${m[1]}}\``)))];
};

const wordCaps = () =>
  ['| Step | Body word cap |', '| --- | ---: |', ...Object.entries(WORD_CAP).map(([step, cap]) => `| ${STEP[step]} | ${cap} |`)].join('\n');

export function templates(library) {
  const trigger = sequenceSkeleton(TRIGGER_LEAD);
  const firstTouch = (heading, skeleton) => [`### ${heading}`, skeletonBlock(place(skeleton.subject), skeleton.emails[0], library)];
  const followUp = step => [`### ${STEP[step]}`, skeletonBlock(library.follow_up_subject, trigger.emails[step - 1], library)];
  return [
    '# Skeletons and snippets',
    'Generated by `npm run render` from `snippets.yaml` and the skeletons in `src/skeleton.js`: do not edit by hand.',
    `In a skeleton's body, each \`{place}\` is filled with one snippet of that type. In the greeting, the snippets, the subject line and the signature, ` +
      `these slots are filled from the contact and its rep: ${slotsIn(library).join(', ')}. ` +
      'In step 1 `{subject}` is the subject snippet; in steps 2 and 3 it is that same rendered subject.',
    '## Skeletons',
    `${STEP[1]}. The lead signal picks one of three. The \`{support}\` place is there only when the contact has a supporting signal.`,
    ...firstTouch('Trigger', trigger),
    ...firstTouch('Lead line', sequenceSkeleton(LEAD_LINE)),
    ...firstTouch('Floor', sequenceSkeleton(FLOOR)),
    'Steps 2 and 3 reply in the step 1 thread.',
    ...followUp(2),
    ...followUp(3),
    '## Snippets',
    'Variant 1 of each snippet is shown; the variants alternate down a company.',
    ...snippetSections(library),
    '## Render checks on the copy',
    'Word caps count the body only: the greeting and signature sit outside them.',
    wordCaps(),
    'Banned phrases: case-insensitive patterns no rendered email may match.',
    library.banned_phrases.map(phrase => `- \`${phrase}\``).join('\n'),
    `No email may name a Humaans customer: ${library.customer_names.join(', ')}.`,
  ].join('\n\n') + '\n';
}
